#!/usr/bin/env node
/**
 * Build the browser half into dist/client.js in the DSH client-module format:
 * one script that calls window.__ModuleLoader__.load({ id, factory }), where the
 * factory receives the module-table `require` and returns the exports. React is
 * the only static external (a shell-seeded platform module); optional host
 * modules such as ui-primitives are reached through the same require at
 * runtime and fall back locally when absent.
 *
 * --check: bundle in memory and validate, without writing dist/.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { runInNewContext } from "node:vm";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "src", "client", "index.jsx");
const out = process.env.WRITER_CLIENT_OUT || path.join(root, "dist", "client.js");
const checkOnly = process.argv.includes("--check");
const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
const ID = process.env.WRITER_CLIENT_ID || 'dsh-zhizhang';

const banner = [
  "/* " + ID + " " + pkg.version + " — browser half (generated by scripts/build-client.mjs; edit src/client/) */",
  "window.__ModuleLoader__.load({",
  "  id: " + JSON.stringify(ID) + ",",
  "  factory: function (require) {",
  "    var module = { exports: {} };",
  "    var exports = module.exports;",
  "    var __dshRequire = require;",
].join("\n");
const footer = ["    return module.exports;", "  },", "});", ""].join("\n");

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "cjs",
  platform: "browser",
  target: ["chrome110", "safari16", "firefox115"],
  jsx: "transform",
  jsxFactory: "React.createElement",
  jsxFragment: "React.Fragment",
  external: ["react"],
  loader: { ".css": "text" },
  define: { __ZZ_CLIENT_ID__: JSON.stringify(ID), __ZZ_VERSION__: JSON.stringify(pkg.version), "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  charset: "utf8",
  minifySyntax: true,
  banner: { js: banner },
  footer: { js: footer },
  logLevel: "silent",
});
const code = result.outputFiles[0].text.trimEnd() + "\n";

// Validate the artifact the same way the host will load it, without a browser.
const forbidden = [/\brequire\(["'](?!react["'])[^"']+["']\)/];
for (const pattern of forbidden) {
  const hit = code.match(pattern);
  if (hit) throw new Error("client bundle has an unexpected static import: " + hit[0]);
}
// Colours belong to the host theme: the stylesheet may only use --dsw-* tokens.
const css = await readFile(path.join(root, "src", "client", "styles.css"), "utf8");
const literal = css.replace(/\/\*[\s\S]*?\*\//g, "").match(/#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|oklch)\(/);
if (literal) throw new Error("client CSS contains a colour literal: " + literal[0]);
let descriptor = null;
runInNewContext(code, {
  window: { __ModuleLoader__: { load: (value) => { descriptor = value; } } },
  console,
});
if (!descriptor || descriptor.id !== ID || typeof descriptor.factory !== "function") {
  throw new Error("client bundle did not register through window.__ModuleLoader__.load");
}
const fakeReact = { createElement: () => null, Component: class {}, Fragment: "f", memo: (c) => c, useState: () => [null, () => {}] };
const exportsObj = descriptor.factory((id) => {
  if (id === "react") return fakeReact;
  throw new Error("missing " + id);
});
for (const name of ["apply", "inject"]) {
  if (!(name in exportsObj)) throw new Error("client bundle does not export " + name);
}

if (checkOnly) {
  console.log("build-client: check ok (" + code.length + " bytes)");
} else {
  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(out, code);
  console.log("build-client: wrote", path.relative(root, out), "(" + code.length + " bytes)");
}
