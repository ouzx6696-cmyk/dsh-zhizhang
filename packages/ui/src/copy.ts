export function t(key: string, vars?: Record<string, unknown>) {
  const raw = Object.prototype.hasOwnProperty.call(COPY, key)
    ? (COPY as Record<string, string>)[key]
    : key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match: string, name: string) =>
    vars[name] == null ? match : String(vars[name]),
  );
}

/** Format an integer the way the copy expects (grouped, zh-CN). */
export function formatCount(n: unknown) {
  const value = Number(n);
  return Number.isFinite(value) ? value.toLocaleString("zh-CN") : "0";
}

/** HH:MM:SS for status lines; empty when the timestamp is unusable. */
export function formatClock(iso?: string) {
  const date = iso ? new Date(iso) : null;
  if (!date || Number.isNaN(date.getTime())) return "";
  return date.toLocaleTimeString("zh-CN", { hour12: false });
}

/** "YYYY-MM-DD HH:mm" in the local timezone; empty when the timestamp is unusable. */
export function formatDateTime(iso?: string) {
  const date = iso ? new Date(iso) : null;
  if (!date || Number.isNaN(date.getTime())) return "";
  const pad = (value: number) => String(value).padStart(2, "0");
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}`;
}

/** 结束文案三处共用（通知、界面 phase、错误解释），文本以通知版为基准。 */
export function taskEndCopy(reason: string | undefined, error?: string): string {
  if (reason === "failed") return `任务失败：${error || "请查看错误后重试"}`;
  if (reason === "cancelled") return "任务已停止，已保存结果保留";
  return "写作任务已结束，等待你查看稿件与回报。";
}

/** Human byte size (KB/MB) for truncation notices. */
export function formatBytes(n: unknown) {
  const value = Number(n) || 0;
  if (value >= 1024 * 1024) return (value / (1024 * 1024)).toFixed(1) + " MB";
  return Math.max(1, Math.round(value / 1024)) + " KB";
}

export function chapterName(chapters: { id: string; title?: string }[], id: string) {
  const index = chapters.findIndex((chapter) => chapter.id === id);
  return index < 0
    ? "相关章节"
    : `第 ${index + 1} 章${chapters[index].title ? `《${chapters[index].title}》` : ""}`;
}
